"""Render research/cbb_halves/RESULTS.md from dev_report.json and test_report.json (no hand-typed numbers)."""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
dev = json.loads((HERE / "results" / "dev_report.json").read_text())
test = json.loads((HERE / "results" / "test_report.json").read_text())
man = json.loads((HERE / "data" / "halves_dataset_manifest.json").read_text())
PER = ["H1", "H2", "H2REG", "HT_H2", "HT_H2REG"]
L = []
f = lambda x, n=3: f"{x:.{n}f}"


def pick(e, shape=None):
    if "chosen" in e:
        return e["chosen"]
    return e[shape or "normal"]


def table(rows_src, title, shapes):
    L.append(f"\n### {title}\n")
    L.append("| Period | Target | n | MAE | RMSE | Bias | Log score | Brier (5 lines) | Log loss (5 lines) | ECE | 50/80/95% coverage | Push pred/obs (int line) |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for p, k, e in rows_src:
        c = e["coverage"]
        L.append(f"| {p} | {k} | {e['n']} | {f(e['mae'])} | {f(e['rmse'])} | {f(e['bias'])} | {f(e['log_score'])} | "
                 f"{f(e['brier_lines'])} | {f(e['logloss_lines'])} | {f(e['ece_lines'])} | "
                 f"{f(c['0.5'],2)}/{f(c['0.8'],2)}/{f(c['0.95'],2)} | {f(e['push_at_integer_line']['pred'])}/{f(e['push_at_integer_line']['obs'])} |")


def splits(rows_src, title):
    L.append(f"\n### {title}\n")
    L.append("| Period | Target | Fav-perspective bias | Fav cover at model line pred/obs | ML fav win pred/obs | ML 2-way Brier / log loss / ECE | ML 3-way Brier / log loss | Tie pred/obs |")
    L.append("|---|---|---|---|---|---|---|---|")
    for p, k, e in rows_src:
        if k != "MARGIN":
            continue
        L.append(f"| {p} | {k} | {f(e['bias_favorite_perspective'])} | {f(e['fav_cover_at_model_line']['pred'])}/{f(e['fav_cover_at_model_line']['obs'])} | "
                 f"{f(e['ml_fav_win']['pred'])}/{f(e['ml_fav_win']['obs'])} | {f(e['ml_twoway_brier'])} / {f(e['ml_twoway_logloss'])} / {f(e['ml_twoway_ece'])} | "
                 f"{f(e['ml3_brier'])} / {f(e['ml3_logloss'])} | {f(e['tie']['pred'])}/{f(e['tie']['obs'])} |")
    L.append("")
    L.append("| Period | Target | Bias (high proj) | Bias (low proj) | Over at model line pred/obs | Under at model line pred/obs |")
    L.append("|---|---|---|---|---|---|")
    for p, k, e in rows_src:
        if k == "MARGIN":
            continue
        L.append(f"| {p} | {k} | {f(e['bias_high_proj'])} | {f(e['bias_low_proj'])} | "
                 f"{f(e['over_at_model_line']['pred'])}/{f(e['over_at_model_line']['obs'])} | "
                 f"{f(e['under_at_model_line']['pred'])}/{f(e['under_at_model_line']['obs'])} |" if "over_at_model_line" in e else
                 f"| {p} | {k} | {f(e['bias_high_proj'])} | {f(e['bias_low_proj'])} | n/a | n/a |")


L.append("# CBB halves model v1: results (PAPER/0u, NON_COUNTED)\n")
L.append(f"Generated by `make_results_md.py`. Dataset sha256 (combined) `{test['dataset_sha256']}`, "
         f"coefficients sha256 `{test['coefficients_sha256']}`.\n")
L.append(f"Dataset: {man['admitted_games']} admitted games, {man['rejected_games']} rejected (reason codes in `data/halves_rejections.csv`).\n")
L.append("| Season | Admitted | Rejected | OT games | Linescore-checked | First tip (UTC) | Last tip (UTC) |")
L.append("|---|---|---|---|---|---|---|")
for y, m in man["by_season"].items():
    L.append(f"| {y} | {m['admitted']} | {m['rejected']} | {m['overtime']} | {m['linescore_checked']} | {m['first_utc']} | {m['last_utc']} |")
L.append("\nRejections by reason: " + ", ".join(f"{k} {v}" for k, v in man["rejections_by_reason"].items()) + "\n")

L.append("## Point-in-time full-game projector (input to the halves model)\n")
L.append("| Season | n | FG margin MAE | FG margin RMSE | FG margin bias | FG total MAE | FG total RMSE | FG total bias |")
L.append("|---|---|---|---|---|---|---|---|")
for s, e in dev["pit_fullgame_by_season"].items():
    L.append(f"| {s} | {e['n']} | {f(e['fg_margin_mae'])} | {f(e['fg_margin_rmse'])} | {f(e['fg_margin_bias'])} | {f(e['fg_total_mae'])} | {f(e['fg_total_rmse'])} | {f(e['fg_total_bias'])} |")

L.append("\n## Untouched test window: season 2026 (scored once)\n")
L.append("Shapes chosen on dev folds: " + ", ".join(f"{k}={v}" for k, v in sorted(test["shapes"].items())) + ".\n")
rows = [(p, k, pick(test["test"][p][k])) for p in PER for k in ("MARGIN", "TOTAL", "TEAM")]
rows += [(f"LEGACY_{p}", k, test["test"][f"LEGACY_{p}"][k]) for p in ("H1", "H2") for k in ("MARGIN", "TOTAL")]
table(rows, "Accuracy, probabilistic scores and calibration (test 2026)", None)
splits(rows, "Favorite/underdog and over/under splits (test 2026)")

L.append("\n## Development folds (rolling origin 2021–2025, mean over folds, normal shape)\n")
drows = []
for p in PER + ["LEGACY_H1", "LEGACY_H2"]:
    for k in ("MARGIN", "TOTAL", "TEAM"):
        es = [dev["folds"][s][p].get(k) for s in dev["folds"]]
        if es[0] is None:
            continue
        es = [e.get("normal", e) for e in es]
        avg = {kk: float(np.mean([e[kk] for e in es])) for kk in ("mae", "rmse", "bias", "log_score", "brier_lines", "logloss_lines", "ece_lines")}
        avg["n"] = int(sum(e["n"] for e in es))
        avg["coverage"] = {c: float(np.mean([e["coverage"][c] for e in es])) for c in ("0.5", "0.8", "0.95")}
        avg["push_at_integer_line"] = {q: float(np.mean([e["push_at_integer_line"][q] for e in es])) for q in ("pred", "obs")}
        drows.append((p, k, avg))
table(drows, "Dev folds pooled (normal shape)", None)
L.append("\nPer-fold bias (normal shape):\n")
L.append("| Fold | " + " | ".join(f"{p} {k}" for p in ("H1", "H2", "HT_H2") for k in ("MARGIN", "TOTAL")) + " |")
L.append("|---|" + "---|" * 6)
for s in dev["folds"]:
    L.append(f"| {s} | " + " | ".join(f(dev['folds'][s][p][k]['normal']['bias'], 2) for p in ("H1", "H2", "HT_H2") for k in ("MARGIN", "TOTAL")) + " |")
L.append("\n## Calibration tables, test 2026 (P(Y > L) at five half-point lines around the mean)\n")
for p in ("H1", "H2", "HT_H2"):
    for k in ("MARGIN", "TOTAL", "TEAM"):
        e = pick(test["test"][p][k])
        L.append(f"**{p} {k}:** " + "; ".join(f"{b['bin']} n={b['n']} pred {b['pred']:.3f} obs {b['obs']:.3f}" for b in e["calibration_lines"]) + "\n")
(HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
print("ok")
