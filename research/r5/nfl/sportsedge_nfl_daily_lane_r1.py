#!/usr/bin/env python3
"""Candidate NFL daily-run orchestration: independently projected scores -> DK board -> V5.

No network scraper or DK credentials are assumed. The user-supplied/captured DK
board is immutable, and imported projections MUST be generated by SportsEdge's
own frozen source input. Fails closed on absent, late, duplicate, stale, mismatched,
or market-derived forecasts. No card becomes OFFICIAL from this script.

Workflow:
 python sportsedge_nfl_daily_lane_r1.py --board board.csv \
   --projections nfl_scores.csv --model-source nfl_ratings.csv \
   --captured-utc 2026-11-12T18:08:00-06:00 \
   --engine sportsedge_v5.py --slate slate_manifest.csv --out out_dir
Without --projections, --model-source, --engine or --slate, it produces an
input audit and BLOCKS with nonzero exit (safe for a scheduled lane).
"""
import argparse
import csv
import hashlib
import json
import math
from collections import Counter
from pathlib import Path

from sportsedge_projection_overlay_r1 import clock, overlay

V5_SHA='72ccaad75b066315f31137f40556321b7057a28119760a6a0b1c2e28da78e02f'
PROJ_COLUMNS=('sport','home','away','home_proj','away_proj','asof_ct','start_ct','model_version','source_file_sha256')
BOARD_COLUMNS=('sport','home','away','home_proj','away_proj','market','price_a','price_b')


def read(path, headers):
    with open(path,newline='',encoding='utf-8-sig') as f:
        rd=csv.DictReader(f)
        fields=rd.fieldnames or []
        if len(fields)!=len(set(fields)) or not set(headers).issubset(fields):
            raise ValueError('HEADERS_INVALID:'+str(set(headers)-set(fields)))
        data=list(rd)
    if any(None in r for r in data):raise ValueError('CSV_OVERFLOW')
    return data


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def game_key(r):
    return tuple(' '.join(r[k].casefold().split()) for k in ('sport','home','away'))


def preflight(board, projection_file=None, source_file=None, captured_utc=None):
    audit={'stage':'NFL_INPUT_PIT','verdict':'BLOCK','refusals':[],
           'board_sha256':sha(board),'projected_games':0,'pricing_invoked':False}
    rows=read(board,BOARD_COLUMNS)
    if not rows:audit['refusals'].append('EMPTY_BOARD')
    if any(r['sport'].upper()!='NFL' for r in rows):audit['refusals'].append('NON_NFL_ROW')
    if any(r['home_proj'].strip() or r['away_proj'].strip() for r in rows):
        audit['refusals'].append('PREFILLED_BOARD_PROJECTION_UNVERIFIABLE')
    games={game_key(r) for r in rows}
    audit['board_rows']=len(rows);audit['board_games']=len(games)
    if not projection_file or not source_file:
        audit['refusals'].append('MISSING_OWN_MODEL_PROJECTIONS_OR_SOURCE')
        return audit
    if not captured_utc or not clock(captured_utc):
        audit['refusals'].append('CAPTURE_TIME_UNVERIFIED');return audit
    capture=clock(captured_utc)
    src_hash=sha(source_file)
    audit['model_source_sha256']=src_hash
    projs=read(projection_file,PROJ_COLUMNS)
    counts=Counter(game_key(r) for r in projs)
    if any(v>1 for v in counts.values()):audit['refusals'].append('DUPLICATE_MODEL_PROJECTION')
    if set(counts)!=games:
        audit['refusals'].append('MISSING_OR_EXTRA_GAME_PROJECTION')
        audit['unmatched_board_games']=[list(x) for x in sorted(games-set(counts))]
        audit['unmatched_model_games']=[list(x) for x in sorted(set(counts)-games)]
    for r in projs:
        name=r.get('model_version','').upper()
        if not name.startswith('SPORTSEDGE_NFL_') or any(x in name for x in ('TORVIK','DRAFTKINGS','ANCHOR','DK_')):
            audit['refusals'].append('FORECAST_SOURCE_NOT_OWN_NFL_MODEL');break
        if r['source_file_sha256'].lower()!=src_hash.lower():
            audit['refusals'].append('FORECAST_SOURCE_HASH_MISMATCH');break
        t1,t2=clock(r['asof_ct']),clock(r['start_ct'])
        if not (t1 and t2 and t1<=capture<t2):
            audit['refusals'].append('FORECAST_PIT_OR_BOARD_CAPTURE_INVALID');break
        try:
            vals=[float(r[k]) for k in ('home_proj','away_proj')]
        except (ValueError,TypeError):vals=[]
        if len(vals)!=2 or not all(math.isfinite(v) and v>0 for v in vals):
            audit['refusals'].append('INVALID_OWN_SCORE_FORECAST');break
    audit['projected_games']=len(counts)
    audit['projections_sha256']=sha(projection_file)
    audit['refusals']=sorted(set(audit['refusals']))
    if not audit['refusals']: audit['verdict']='PIT_READY_FOR_GUARDED_V5'
    return audit


def run(board, projections, model_source, captured_utc, engine, slate, out, preflight_only=False):
    path=Path(out);path.mkdir(parents=True,exist_ok=True)
    report=path/'nfl_daily_lane_report.json'
    try:audit=preflight(board,projections,model_source,captured_utc)
    except (ValueError,KeyError,FileNotFoundError) as ex:
        audit={'stage':'NFL_INPUT_PIT','verdict':'BLOCK','refusals':['INPUT_READ_OR_FORMAT:'+str(ex)],'pricing_invoked':False}
    audit['status']='CANDIDATE_PAPER_0U_NO_OFFICIAL_BETS'
    audit['engine_unchanged']=True
    if audit['verdict']=='BLOCK':
        report.write_text(json.dumps(audit,indent=2)+'\n');return audit
    if not engine or not slate:
        audit.update(verdict='BLOCK',refusals=['ENGINE_OR_COMPLETE_SLATE_MANIFEST_MISSING'])
        report.write_text(json.dumps(audit,indent=2)+'\n');return audit
    if sha(engine)!=V5_SHA:
        audit.update(verdict='BLOCK',refusals=['ENGINE_SHA_NOT_V5_OF_RECORD'])
        report.write_text(json.dumps(audit,indent=2)+'\n');return audit
    decorated=path/'nfl_board_with_own_projections.csv'
    over_report=path/'projection_overlay_report.json'
    ol=overlay(board,projections,decorated,over_report)
    if ol['projection_problems'] or ol['updated_rows']!=audit['board_rows']:
        audit.update(verdict='BLOCK',refusals=['OVERLAY_INCOMPLETE_OR_INVALID'])
        report.write_text(json.dumps(audit,indent=2)+'\n');return audit
    # Import only after source/PIT checks. The guarded runner validates the
    # complete slate, exact v5 bytes, each quote and every game output.
    from sportsedge_guarded_v5_runner_r2 import run_guarded
    gr=run_guarded(decorated,engine,path/'guarded_v5',slate=slate,
                   research_anchor=False,run_engine=not preflight_only)
    audit['guarded_runner']=gr
    audit['pricing_invoked']=gr.get('pricing_invoked',False)
    audit['verdict']='PREFLIGHT_PASS' if gr.get('verdict')=='PREFLIGHT_PASS' else (
        'RESEARCH_RUN_COMPLETE' if gr.get('verdict')=='RESEARCH_RUN_COMPLETE' else 'BLOCK')
    if audit['verdict']=='BLOCK':audit['refusals']=['GUARDED_V5_'+str(gr.get('reason','UNKNOWN'))]
    report.write_text(json.dumps(audit,indent=2)+'\n')
    return audit


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--board',required=True)
    p.add_argument('--projections');p.add_argument('--model-source');p.add_argument('--captured-utc')
    p.add_argument('--engine');p.add_argument('--slate');p.add_argument('--out',required=True)
    p.add_argument('--preflight-only',action='store_true')
    a=p.parse_args()
    z=run(a.board,a.projections,a.model_source,a.captured_utc,a.engine,a.slate,a.out,a.preflight_only)
    print(json.dumps({'verdict':z['verdict'],'refusals':z.get('refusals'),
                      'board_rows':z.get('board_rows'),'projected_games':z.get('projected_games')}))
    if z['verdict']=='BLOCK':raise SystemExit(2)

if __name__=='__main__':main()
